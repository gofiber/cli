// The Source type of the session middleware of Fiber v2 (session.Source) is a
// string of its own. It is written as a plain string, and its constants as the
// strings they stood for, unless the program asks for the type: where it tells a
// Source from a string (a type switch, a type assertion), the two have to stay
// apart, and where it declares the identifier string itself (and cannot name the
// builtin type) there is nothing to write it as. The module then gets the type in
// its package <module>/internal/fibermigrate, as SessionSource and the constants
// SessionSourceCookie, SessionSourceHeader and SessionSourceURLQuery, and every
// file of the module uses it, because the values meet in the code of the project.
// Its source is sessionshim/session.go, a package of its own so that it is built,
// vetted, linted and tested with the CLI.
const (
	// sessionShimFile is the name of the file in the module package.
	sessionShimFile   = "session.go"
	sessionShimMarker = `This file was added by "fiber migrate": the type of the place a session ID is read from in Fiber v2`
	// sessionShimPackage is the package clause of the source file.
	sessionShimPackage = "\npackage sessionshim\n"
	// sessionShimType is the type that takes the place of session.Source.
	sessionShimType = "SessionSource"
)

// sessionShimHeader is what the file starts with. The code follows the package
// clause.
const sessionShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + sessionShimMarker + `
// (session.Source). Fiber v3 removed it, its session middleware reads a session ID with an
// Extractor. The program told the type apart from a plain string, or could not name string,
// so the type stays: it is a string of its own, as it was. Delete the file once the program no
// longer needs the difference.

`

//go:embed sessionshim/session.go
var sessionShimSource string

// sessionShimLint matches the directive of a linter that is written before a
// comment in the source.
var sessionShimLint = regexp.MustCompile(`//nolint:[\w,]+ // `)

// sessionShimBody is the code of the file: the source without its package clause
// and the comment above it.
var sessionShimBody = sync.OnceValue(func() string {
	_, body, _ := strings.Cut(sessionShimSource, sessionShimPackage)
	return sessionShimLint.ReplaceAllString(body, "// ")
})

// sessionShimModuleFile describes the file with the type.
func sessionShimModuleFile() moduleShimFile {
	return moduleShimFile{
		name:   sessionShimFile,
		marker: sessionShimMarker,
		source: sessionShimHeader + "package " + moduleShimPkg + "\n" + sessionShimBody(),
	}
}

// mw3SourceConstants are the constants of the Source type: the name in the session
// package, the name of the constant that takes its place in the module package,
// and the string it stood for.
var mw3SourceConstants = []struct{ name, shim, value string }{
	{"SourceCookie", "SessionSourceCookie", mw3SourceCookie},
	{"SourceHeader", "SessionSourceHeader", mw3SourceHeader},
	{"SourceURLQuery", "SessionSourceURLQuery", mw3SourceQuery},
}

// sessionShimConstants are the constants of the type of the module package, by the
// name of the constant of the session package whose place they take.
var sessionShimConstants = func() map[string]string {
	names := map[string]string{}
	for _, c := range mw3SourceConstants {
		names[c.name] = c.shim
	}
	return names
}()

// mw3SourceMode is what a module does with the Source type: it is a plain string,
// or the type of the module package, which path is the import path of.
type mw3SourceMode struct {
	// path is the import path of the module package that has the type, empty when
	// the type is string.
	path string
	// missing is set when the program needs the type and the module cannot have it:
	// it is outside of a module, or the package of the shims holds code that the
	// migrations did not write.
	missing bool
}

// sourceMode returns what the module of the file does with the Source type. It
// is decided once for the module, before any file of it is rewritten, because the
// types of the files have to agree.
func (p *mw3Pkgs) sourceMode(fi internal.FileInfo) *mw3SourceMode {
	mod, ok := moduleOf(fi.Path, fi.Root)
	if !ok {
		return &mw3SourceMode{}
	}
	if mode, done := p.sources[mod.root]; done {
		return mode
	}
	if p.sources == nil {
		p.sources = map[string]*mw3SourceMode{}
	}

	mode := &mw3SourceMode{}
	p.sources[mod.root] = mode
	if p.indexes.of(fi).needsSourceType() {
		if path, shimmed := ensureModuleShim(fi, sessionShimModuleFile()); shimmed {
			mode.path = path
		} else {
			mode.missing = true
		}
	}
	return mode
}

// mw3SessionPaths are the import paths of the session middleware of the major
// versions of Fiber that have it.
var mw3SessionPaths = []string{
	"github.com/gofiber/fiber/v2/middleware/session",
	"github.com/gofiber/fiber/v3/middleware/session",
}

// needsSourceType reports whether a file of the module tells the Source type of
// the session middleware from a string, or cannot write string where it uses the
// type.
func (ix *moduleIndex) needsSourceType() bool {
	return slices.ContainsFunc(mw3SessionPaths, func(path string) bool {
		return slices.ContainsFunc(ix.importers(path), ix.fileNeedsSourceType)
	})
}

// fileNeedsSourceType is needsSourceType for one file that imports the session
// middleware.
func (ix *moduleIndex) fileNeedsSourceType(f *modFile) bool {
	names := f.importNames(mw3SessionPath, "session")
	if len(names) == 0 || !strings.Contains(f.g.src, mw3SessionSource) {
		return false
	}

	isSource := func(e ast.Expr, pos token.Pos, stack []ast.Node) bool {
		sel, ok := e.(*ast.SelectorExpr)
		if !ok || sel.Sel.Name != mw3SessionSource {
			return false
		}
		id, ok := sel.X.(*ast.Ident)
		return ok && slices.Contains(names, id.Name) && !mw3Shadowed(id.Name, pos, stack)
	}

	// Where the file cannot name string, the type is all there is.
	ix.packageIn(filepath.Dir(f.path))
	_, hidesString := mw3DeclaredNames(f.g.file)["string"]
	hidesString = hidesString || f.pkg.lookupIn(f, "string") != nil

	needs := false
	f.g.walk(func(n ast.Node, stack []ast.Node) bool {
		switch n := n.(type) {
		case *ast.TypeAssertExpr:
			needs = needs || (n.Type != nil && isSource(n.Type, n.Type.Pos(), stack))
		case *ast.TypeSwitchStmt:
			inner := append(slices.Clone(stack), n)
			for _, stmt := range n.Body.List {
				clause, ok := stmt.(*ast.CaseClause)
				if !ok {
					continue
				}
				for _, e := range clause.List {
					needs = needs || isSource(e, e.Pos(), inner)
				}
			}
		case *ast.SwitchStmt:
			// The cases of a switch on an interface can be a Source and the string
			// that has the same value, which are two cases of different types.
			needs = needs || (n.Tag != nil && mw3SourceTwice(mw3CaseExprs(n), names, stack))
		case *ast.CompositeLit:
			if _, isMap := n.Type.(*ast.MapType); isMap {
				needs = needs || mw3SourceTwice(mw3MapKeys(n), names, stack)
			}
		case *ast.BinaryExpr:
			// A union of types, in the constraint of a type parameter, has the Source
			// and the string as two terms.
			needs = needs || (n.Op == token.OR && (isSource(mw3UnionTerm(n.X), n.Pos(), stack) || isSource(mw3UnionTerm(n.Y), n.Pos(), stack)))
		case *ast.SelectorExpr:
			if hidesString && (isSource(n, n.Pos(), stack) || mw3IsSourceConstant(n, names, stack)) {
				needs = true
			}
		}
		return !needs
	})
	return needs
}

// mw3UnionTerm returns the type of a term of a union, which may be written ~T.
func mw3UnionTerm(e ast.Expr) ast.Expr {
	if u, ok := e.(*ast.UnaryExpr); ok && u.Op == token.TILDE {
		return u.X
	}
	return e
}

// mw3CaseExprs returns the values of the cases of a switch.
func mw3CaseExprs(sw *ast.SwitchStmt) []ast.Expr {
	var exprs []ast.Expr
	for _, stmt := range sw.Body.List {
		if clause, ok := stmt.(*ast.CaseClause); ok {
			exprs = append(exprs, clause.List...)
		}
	}
	return exprs
}

// mw3MapKeys returns the keys of a map literal.
func mw3MapKeys(lit *ast.CompositeLit) []ast.Expr {
	var keys []ast.Expr
	for _, elt := range lit.Elts {
		if kv, ok := elt.(*ast.KeyValueExpr); ok {
			keys = append(keys, kv.Key)
		}
	}
	return keys
}

// mw3SourceTwice reports whether the values hold a constant of the Source type and
// a string literal with the same value: once both are strings they would be one.
func mw3SourceTwice(values []ast.Expr, names []string, stack []ast.Node) bool {
	typed, plain := map[string]struct{}{}, map[string]struct{}{}
	for _, e := range values {
		switch x := ast.Unparen(e).(type) {
		case *ast.SelectorExpr:
			if mw3IsSourceConstant(x, names, stack) {
				typed[mw3SessionSourceValues[x.Sel.Name]] = struct{}{}
			}
		case *ast.BasicLit:
			if value, ok := mw3UnquoteString(x); ok {
				plain[value] = struct{}{}
			}
		}
	}
	for value := range typed {
		if _, twice := plain[value]; twice {
			return true
		}
	}
	return false
}

// mw3IsSourceConstant reports whether the selector is one of the constants of the
// Source type, through one of the names of the session package.
func mw3IsSourceConstant(sel *ast.SelectorExpr, names []string, stack []ast.Node) bool {
	if _, ok := sessionShimConstants[sel.Sel.Name]; !ok {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	return ok && slices.Contains(names, id.Name) && !mw3Shadowed(id.Name, sel.Pos(), stack)
}

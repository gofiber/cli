// Conn() of the postgres storage returned a *sql.DB until the v3 line of the
// module (github.com/gofiber/storage/postgres/v3), which returns the
// *pgxpool.Pool of the storage. The code that moved with the import keeps getting a
// *sql.DB: the call is wrapped in PostgresDB, a function that the migration adds to
// the module package (<module>/internal/fibermigrate/postgres.go) and that makes
// one *sql.DB for each pool with stdlib.OpenDBFromPool, so that calling it for every
// request does not leave a database behind each time. The calls are found on the
// values the declarations say are such a storage, wherever they are in the module.

var (
	// importsPostgresOld is the import path of the postgres storage without a major
	// version, the one whose Conn() returned a *sql.DB.
	importsPostgresOld = "github.com/gofiber/storage/postgres"
	// importsPostgresAny matches the import path of the postgres storage at any
	// version.
	importsPostgresAny = regexp.MustCompile(`^github\.com/gofiber/storage/postgres(/v\d+)?$`)
)

// The kinds of values the oracle tells apart; 0 is a value that cannot be told.
const (
	pgUnknown uint8 = iota
	// pgMoved is a postgres storage whose import the migration moves to the v3 line.
	pgMoved
	// pgOther is a value that is known not to be one.
	pgOther
)

const (
	pgShimFile   = "postgres.go"
	pgShimMarker = `This file was added by "fiber migrate": the database/sql view of the pool of the postgres storage`
	// pgShimPackage is the package clause of the source, which is not built with the CLI.
	pgShimPackage = "\npackage postgresshim\n"
)

// pgShimHeader is what the file starts with. The code follows the package clause.
const pgShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + pgShimMarker + `.
// github.com/gofiber/storage/postgres returned a *sql.DB from Conn() until its v3, which
// returns the *pgxpool.Pool of the storage. PostgresDB gives the code that still uses
// database/sql that *sql.DB, once for each pool. Delete the file when the code uses the
// pool, or pgx, itself.
`

// pgShimSource is the source of the file. It is built in a module of its own by the
// tests, since the CLI does not depend on pgx.
//
//go:embed postgresshim/postgres.go
var pgShimSource string

// pgShimModuleFile is the file as it is added to the module package.
func pgShimModuleFile() moduleShimFile {
	_, body, _ := strings.Cut(pgShimSource, pgShimPackage)
	return moduleShimFile{
		name:   pgShimFile,
		marker: pgShimMarker,
		source: pgShimHeader + "\npackage " + moduleShimPkg + "\n" + body,
	}
}

// importsStorageScan is the state of one run of MigrateStorageVersions.
type importsStorageScan struct {
	indexes moduleIndexes
	cache   kindTablesCache
	// moving are the files that import the postgres storage without a major
	// version, where Conn() returned a *sql.DB: their import is moved to the v3
	// line. It is what the files were before the run, so that the answer does not
	// depend on the order they are visited in.
	moving  map[string]bool
	views   map[*modFile]*importsPostgresView
	changed []string
}

// plan reads the files before any of them is written.
func (r *importsStorageScan) plan(cwd string) {
	r.moving = map[string]bool{}
	//nolint:errcheck // a tree that cannot be read is migrated, or reported, by the pass that writes it
	_, _ = internal.ChangeFileContentInfo(cwd, func(content string, fi internal.FileInfo) string {
		if strings.Contains(content, importsPostgresOld) && importsImportsPath(content, importsPostgresOld) {
			r.moving[fi.Path] = true
		}
		return content
	})
}

// importsImportsPath reports whether the source imports the package.
func importsImportsPath(src, importPath string) bool {
	file, err := parser.ParseFile(token.NewFileSet(), "", src, parser.ImportsOnly)
	if err != nil && file == nil {
		return false
	}
	for _, spec := range file.Imports {
		if p, unquoteErr := strconv.Unquote(spec.Path.Value); unquoteErr == nil && p == importPath {
			return true
		}
	}
	return false
}

// refresh makes the indexes forget the files that the run has written.
func (r *importsStorageScan) refresh() {
	if len(r.changed) == 0 {
		return
	}
	for _, ix := range r.indexes.byRoot {
		ix.invalidate(r.changed...)
	}
	r.changed = nil
	clear(r.views)
}

// importsPostgresView answers the questions about the postgres storages in one
// file.
type importsPostgresView struct {
	run *importsStorageScan
	g   *goSource
	// mf is the file as the module index sees it, nil outside of a module.
	mf *modFile
	// names are the identifiers the file binds to the postgres storage.
	names []string
	// moved says the file imports the storage without a major version.
	moved bool
}

// viewOf returns the questions about a file of the module as the index reads it.
func (r *importsStorageScan) viewOf(mf *modFile) *importsPostgresView {
	if v := r.views[mf]; v != nil {
		return v
	}
	if r.views == nil {
		r.views = map[*modFile]*importsPostgresView{}
	}
	v := &importsPostgresView{run: r, g: mf.g, mf: mf, moved: r.moving[mf.path]}
	for _, spec := range importsOf(mf.g, importsPostgresAny.MatchString) {
		if !spec.blank() && !spec.dot() {
			v.names = append(v.names, spec.local("postgres"))
		}
	}
	r.views[mf] = v
	return v
}

// typeKind says what a value of the type is.
func (v *importsPostgresView) typeKind(t ast.Expr, stack []ast.Node) uint8 {
	for {
		switch x := t.(type) {
		case *ast.StarExpr:
			t = x.X
			continue
		case *ast.ParenExpr:
			t = x.X
			continue
		case *ast.SelectorExpr:
			if id, ok := x.X.(*ast.Ident); ok && v.isPackage(id, stack) {
				if x.Sel.Name == "Storage" && v.moved {
					return pgMoved
				}
				return pgOther
			}
		}
		return pgUnknown
	}
}

// declaredKind is typeKind for a type that a declaration names: one that is not
// the storage is another kind of value, not an unknown one.
func (v *importsPostgresView) declaredKind(t ast.Expr, stack []ast.Node) uint8 {
	if k := v.typeKind(t, stack); k != pgUnknown {
		return k
	}
	return pgOther
}

// isPackage reports whether the identifier names the postgres package here and not
// a variable that has the same name.
func (v *importsPostgresView) isPackage(id *ast.Ident, stack []ast.Node) bool {
	if !slices.Contains(v.names, id.Name) {
		return false
	}
	if stack == nil {
		return true
	}
	_, hidden := resolveIdent(id.Name, id.Pos(), stack)
	return !hidden && !modDeclaredLocally(id.Name, id.Pos(), stack)
}

// kindOf says what the value of e is, where the ancestors of e are stack.
func (v *importsPostgresView) kindOf(e ast.Expr, stack []ast.Node) uint8 {
	return v.kindAt(e, stack, 0)
}

func (v *importsPostgresView) kindAt(e ast.Expr, stack []ast.Node, depth int) uint8 {
	if depth > importsMaxDepth+sentryMaxDepth {
		return pgUnknown
	}

	switch x := e.(type) {
	case *ast.ParenExpr:
		return v.kindAt(x.X, stack, depth+1)
	case *ast.StarExpr:
		return v.kindAt(x.X, stack, depth+1)
	case *ast.UnaryExpr:
		if x.Op == token.AND {
			return v.kindAt(x.X, stack, depth+1)
		}
	case *ast.CompositeLit:
		if x.Type != nil {
			return v.declaredKind(x.Type, stack)
		}
	case *ast.TypeAssertExpr:
		if x.Type != nil {
			return v.declaredKind(x.Type, stack)
		}
	case *ast.CallExpr:
		return v.callKind(x, stack, depth)
	case *ast.Ident:
		return v.identKind(x, stack, depth)
	case *ast.SelectorExpr:
		return v.selectorKind(x, stack, depth)
	}
	return pgUnknown
}

func (v *importsPostgresView) callKind(call *ast.CallExpr, stack []ast.Node, depth int) uint8 {
	switch fun := ast.Unparen(call.Fun).(type) {
	case *ast.SelectorExpr:
		if id, ok := fun.X.(*ast.Ident); ok {
			if v.isPackage(id, stack) {
				if fun.Sel.Name == mw2New && v.moved {
					return pgMoved
				}
				return pgOther
			}
			if v.isImport(id, stack) {
				return v.declKind(v.mf.declOf(fun), depth)
			}
		}
		if t, ok := exprType(v.mf, call, stack, 0); ok {
			if kind := v.run.modTypeKind(t); kind != pgUnknown {
				return kind
			}
		}
		return v.run.methodKind(v, fun.Sel.Name)
	case *ast.Ident:
		if v.mf != nil && !modDeclaredLocally(fun.Name, fun.Pos(), stack) {
			return v.declKind(v.mf.declOf(fun), depth)
		}
	}
	return pgUnknown
}

// isImport reports whether the identifier names a package of the module that the
// file imports.
func (v *importsPostgresView) isImport(id *ast.Ident, stack []ast.Node) bool {
	if v.mf == nil || modDeclaredLocally(id.Name, id.Pos(), stack) {
		return false
	}
	_, ok := v.mf.importFor(id.Name)
	return ok
}

func (v *importsPostgresView) identKind(id *ast.Ident, stack []ast.Node, depth int) uint8 {
	if d, ok := resolveIdent(id.Name, id.Pos(), stack); ok {
		switch {
		case d.typ != nil:
			return v.declaredKind(d.typ, stack)
		case d.init != nil:
			return v.kindAt(d.init, stack, depth+1)
		}
		return pgUnknown
	}
	if v.mf != nil && !modDeclaredLocally(id.Name, id.Pos(), stack) {
		return v.declKind(v.mf.declOf(id), depth)
	}
	return pgUnknown
}

func (v *importsPostgresView) selectorKind(sel *ast.SelectorExpr, stack []ast.Node, depth int) uint8 {
	if id, ok := sel.X.(*ast.Ident); ok && v.isImport(id, stack) {
		return v.declKind(v.mf.declOf(sel), depth)
	}
	if t, ok := exprType(v.mf, sel, stack, 0); ok {
		if kind := v.run.modTypeKind(t); kind != pgUnknown {
			return kind
		}
	}
	return v.run.fieldKind(v, sel.Sel.Name)
}

// declKind says what a declaration of the module holds: a variable, or the first
// result of a function.
func (v *importsPostgresView) declKind(d *modDecl, depth int) uint8 {
	if d == nil || d.dup || depth > importsMaxDepth+sentryMaxDepth {
		return pgUnknown
	}

	switch d.kind {
	case modFunc, modMethod:
		if results := d.results(); len(results) > 0 {
			return v.run.modTypeKind(results[0])
		}
	case modVar:
		if t, ok := d.varType(); ok {
			return v.run.modTypeKind(t)
		}
		if e, idx, ok := d.varInit(); ok && idx == 0 {
			return v.run.viewOf(d.file).kindAt(e, nil, depth+1)
		}
	default:
		// a constant or a type is not a storage
	}
	return pgUnknown
}

// modTypeKind says what a value of a type written in a file of the module is.
func (r *importsStorageScan) modTypeKind(t modType) uint8 {
	if kind := r.viewOf(t.file).typeKind(t.expr, nil); kind != pgUnknown {
		return kind
	}
	if _, ok := t.named(); ok {
		return pgOther
	}
	return pgUnknown
}

func (r *importsStorageScan) tables(v *importsPostgresView) kindTables {
	return r.cache.of(v.mf, v.g,
		r.modTypeKind,
		func(t ast.Expr) uint8 { return v.declaredKind(t, nil) })
}

func (r *importsStorageScan) fieldKind(v *importsPostgresView, name string) uint8 {
	return r.tables(v).fields[name]
}

func (r *importsStorageScan) methodKind(v *importsPostgresView, name string) uint8 {
	return r.tables(v).methods[name]
}

// conn migrates the call of Conn() on a postgres storage whose import moves to
// the v3 line: the call returns a *pgxpool.Pool there, and the code that gets a
// *sql.DB from it gets the view of the pool that the module package makes.
func (s *importsStorageFile) conn(call *ast.CallExpr, stack []ast.Node) {
	sel, ok := call.Fun.(*ast.SelectorExpr)
	if !ok || sel.Sel.Name != "Conn" || len(call.Args) != 0 {
		return
	}

	if s.pg != nil && s.pg.kindOf(sel.X, stack) == pgMoved {
		s.wrapConn(call, stack)
		return
	}
	s.noteConn(call, stack)
}

// wrapConn wraps the call in PostgresDB, or reports it when the module cannot have
// the function.
func (s *importsStorageFile) wrapConn(call *ast.CallExpr, stack []ast.Node) {
	shimPath, ok := ensureModuleShim(s.fi, pgShimModuleFile())
	if !ok {
		internal.Notef(s.fi, s.g.line(call.Pos()), "%s",
			"`Conn()` returns a *pgxpool.Pool in github.com/gofiber/storage/postgres/v3, it returned a *sql.DB in the module without a major version: "+
				"adapt the code that uses the connection.")
		return
	}

	name, add := mw1ImportName(s.g.src, shimPath, moduleShimPkg)
	if add {
		s.needShim = shimPath
	}
	if importsShadowed(name, call.Pos(), stack) {
		// a local called like the package: the call cannot name it here
		internal.Notef(s.fi, s.g.line(call.Pos()),
			"`Conn()` returns a *pgxpool.Pool in github.com/gofiber/storage/postgres/v3, it returned a *sql.DB in the module without a major version: "+
				"wrap it in PostgresDB of %s (a local called %s hides the package here).", shimPath, name)
		return
	}

	text := s.g.text(call)
	s.edits.replaceNode(s.g, call, name+".PostgresDB("+text+")")
	s.usesShim = true
	s.reportPoolSettings(call, stack)
}

// sqlPoolSettings are the methods of *sql.DB that size its pool.
var sqlPoolSettings = []string{"SetMaxOpenConns", "SetMaxIdleConns", "SetConnMaxLifetime", "SetConnMaxIdleTime"}

// reportPoolSettings tells about the settings of the pool that were made on the
// *sql.DB of the storage: they limit the view of the pool now, not the pool.
func (s *importsStorageFile) reportPoolSettings(call *ast.CallExpr, stack []ast.Node) {
	if len(stack) == 0 {
		return
	}
	parent, ok := stack[len(stack)-1].(*ast.SelectorExpr)
	if !ok || parent.X != ast.Expr(call) {
		return
	}

	switch {
	case slices.Contains(sqlPoolSettings, parent.Sel.Name):
		internal.Notef(s.fi, s.g.line(call.Pos()),
			"%s of the storage's *sql.DB limits the database/sql view of its pool in the v3 line of the postgres storage, not the pool: "+
				"size the pool with pool_max_conns, pool_min_conns, pool_max_conn_lifetime and pool_max_conn_idle_time in Config.ConnectionURI, or give the storage a pool of your own in Config.DB.",
			parent.Sel.Name)
	case parent.Sel.Name == "Close":
		internal.Notef(s.fi, s.g.line(call.Pos()), "%s",
			"Close of the storage's *sql.DB closes the database/sql view of its pool in the v3 line of the postgres storage, not the pool: close the storage to close the pool.")
	}
}

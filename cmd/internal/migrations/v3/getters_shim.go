package v3

import (
	"strings"

	_ "embed" // the source of the file that holds ParamsInt and QueryFloat of Fiber v2

	"github.com/gofiber/cli/cmd/internal"
)

// The helpers of Fiber v3 that take the place of ParamsInt and QueryFloat do not do the same
// as the methods of v2. QueryFloat read every number strconv.ParseFloat reads, and
// fiber.Query[float64] reads decimal numbers only (it gives the default for inf, nan, a
// hexadecimal number and one with underscores, and for the numbers at the ends of the range
// of a float64); ParamsInt returned an error that reads "failed to convert: " before the one of
// strconv.Atoi, which strconv.Atoi(c.Params(key)) does not say, and the default error handler
// puts the text of an error into the response. A call whose result can show the difference
// goes to the ParamsInt or the QueryFloat of the module package instead
// (<module>/internal/fibermigrate/getters.go), the method of v2 on the context of v3. Its
// source is gettershim/getters.go.
const (
	// getterShimFile is the name of the file in the module package.
	getterShimFile = "getters.go"
	// getterShimMarker is what a later run finds in the file to know that it was added by a
	// migration.
	getterShimMarker = `This file was added by "fiber migrate": ParamsInt and QueryFloat of Fiber v2`
	// getterShimPackage is the package clause of the source, which is a package of the CLI.
	getterShimPackage = "\npackage gettershim\n"
)

// getterShimHeader is what the file starts with. The code follows the package clause.
const getterShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + getterShimMarker + `.
// ParamsInt returns 0 and an error that reads "failed to convert: " and the error of strconv.Atoi for
// a parameter that is no integer, and QueryFloat reads every number that strconv.ParseFloat reads
// (inf and nan, hexadecimal numbers, underscores between the digits, the ends of the range of a float64).
// fiber.Params[int] and fiber.Query[float64] of Fiber v3 read decimal numbers only and say nothing of
// the error. Delete the file once the code calls those instead and the difference does not matter.
`

//go:embed gettershim/getters.go
var getterShimEmbedded string

// getterShimSource is the source with the line ends of Unix.
var getterShimSource = shimUnixLines(getterShimEmbedded)

// getterShimModuleFile is the file as it is added to the module package.
func getterShimModuleFile() moduleShimFile {
	_, body, _ := strings.Cut(getterShimSource, getterShimPackage)
	return moduleShimFile{
		name:   getterShimFile,
		marker: getterShimMarker,
		source: getterShimHeader + "\npackage " + moduleShimPkg + "\n" + body,
	}
}

// getterShim is what a file knows about the ParamsInt and the QueryFloat of the package of its
// module.
type getterShim struct {
	// path is the import path of the module package.
	path string
	fi   internal.FileInfo
	// tried says the module was asked for the file, ok that it has it.
	tried, ok bool
}

// available makes sure the module of the file has the getters, adding them on first use, and
// reports whether it does. A file outside of a module, or a package that holds code the
// migrations did not write, cannot have them.
func (s *getterShim) available() bool {
	if !s.tried {
		s.tried = true
		s.path, s.ok = ensureModuleShim(s.fi, getterShimModuleFile())
	}
	return s.ok
}

func Test_clientShim_GeneratedFile(t *testing.T) {
	t.Parallel()

	gf := clientShimGenerated()
	assert.Equal(t, clientShimFile, gf.name)
	assert.Equal(t, 1, strings.Count(gf.source, generatedPkgPlaceholder), "the package name goes in one place")
	assert.Contains(t, gf.source, gf.marker, "a second run finds the file by its marker")
	assert.Contains(t, gf.source, "github.com/gofiber/fiber/v3/client", "the header says what to move to")

	// The code below the package clause is the code of the agentshim package.
	header, body, ok := strings.Cut(gf.source, "package "+generatedPkgPlaceholder+"\n")
	require.True(t, ok)
	_, want, ok := strings.Cut(clientShimSource, clientShimPackage)
	require.True(t, ok)
	assert.Equal(t, want, body)
	assert.Regexp(t, `^// Code generated by "fiber migrate"; DO NOT EDIT\.\n`, header, "linters leave a generated file alone")

	// With the name of a package, it is Go that gofmt leaves as it is.
	src := strings.ReplaceAll(gf.source, generatedPkgPlaceholder, "app")
	formatted, err := format.Source([]byte(src))
	require.NoError(t, err)
	assert.Equal(t, src, string(formatted))

	file, err := parser.ParseFile(token.NewFileSet(), clientShimFile, src, parser.ParseComments)
	require.NoError(t, err)
	assert.Equal(t, "app", file.Name.Name)
}

// clientShimDeclared parses the code the project gets and returns its imports and
// its top level declarations.
func clientShimDeclared(t *testing.T) (imports []*ast.ImportSpec, names map[string]ast.Node) {
	t.Helper()

	src := strings.ReplaceAll(clientShimGenerated().source, generatedPkgPlaceholder, "app")
	file, err := parser.ParseFile(token.NewFileSet(), clientShimFile, src, parser.SkipObjectResolution)
	require.NoError(t, err)

	names = map[string]ast.Node{}
	for _, d := range file.Decls {
		switch decl := d.(type) {
		case *ast.FuncDecl:
			if decl.Recv == nil {
				names[decl.Name.Name] = decl
			}
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					names[s.Name.Name] = s
				case *ast.ValueSpec:
					for _, id := range s.Names {
						names[id.Name] = s
					}
				}
			}
		}
	}
	return file.Imports, names
}

func Test_clientShim_CannotCollideWithTheProject(t *testing.T) {
	t.Parallel()

	imports, names := clientShimDeclared(t)
	require.NotEmpty(t, names)

	for name := range names {
		assert.True(t, strings.HasPrefix(name, clientShimPrefix), "%s starts with the prefix", name)
		assert.False(t, ast.IsExported(name), "%s is unexported", name)
	}

	// An import is renamed as well: a package level name of the project (a json
	// variable, say) must not clash with it.
	for _, spec := range imports {
		path, err := strconv.Unquote(spec.Path.Value)
		require.NoError(t, err)
		require.NotNil(t, spec.Name, "%s has a name of its own", path)
		assert.NotEqual(t, defaultImportName(path), spec.Name.Name)
		assert.True(t, strings.HasPrefix(spec.Name.Name, "fm"), "%s is named %s", path, spec.Name.Name)

		// Only the standard library and fasthttp.
		first, _, _ := strings.Cut(path, "/")
		assert.True(t, !strings.Contains(first, ".") || path == "github.com/valyala/fasthttp", "%s is no dependency of the copy", path)
	}

	// The helper looks for exactly these names in the package.
	idents := clientShimIdents()
	for name := range names {
		assert.Contains(t, idents, name)
	}
	for _, spec := range imports {
		assert.Contains(t, idents, spec.Name.Name)
	}
	assert.Len(t, idents, len(names)+len(imports))
}

func Test_clientShim_MembersAreDeclared(t *testing.T) {
	t.Parallel()

	_, names := clientShimDeclared(t)
	for member := range clientShimMembers {
		assert.Contains(t, names, clientShimPrefix+member, "the copy declares %s", member)
	}

	// Every member of the removed client is either the copy's or an alias of fasthttp.
	for _, member := range clientAPIMembers {
		_, copied := clientShimMembers[member]
		assert.True(t, copied || slices.Contains(clientFasthttpAliases, member), "%s has a place to go", member)
	}
}

func Test_clientShim_CoversTheRemovedClientNames(t *testing.T) {
	t.Parallel()

	// Every member of the fiber package that Fiber v3 removed with the HTTP client
	// is either the copy's or an alias of fasthttp.
	found := 0
	for qualified, hint := range reviewAdvice {
		name, ok := strings.CutPrefix(qualified, reviewCorePath+".")
		if !ok || hint != reviewClientHint {
			continue
		}
		found++
		_, copied := clientShimMembers[name]
		assert.True(t, copied || slices.Contains(clientFasthttpAliases, name), "%s has a place to go", name)
	}
	assert.Equal(t, len(clientShimMembers)+len(clientFasthttpAliases), found)
}

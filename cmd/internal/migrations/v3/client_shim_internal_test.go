func Test_clientShim_ModuleFile(t *testing.T) {
	t.Parallel()

	mf := clientShimModuleFile()
	assert.Equal(t, clientShimFile, mf.name)
	assert.Contains(t, mf.source, mf.marker, "a second run finds the file by its marker")
	assert.Contains(t, mf.marker, moduleShimMarker, "the package finds out that a migration wrote the file")
	assert.Contains(t, mf.source, "github.com/gofiber/fiber/v3/client", "the header says what to move to")

	// The code below the package clause is the code of the agentshim package, without
	// the directives of the linters of the CLI.
	header, body, ok := strings.Cut(mf.source, "package "+moduleShimPkg+"\n")
	require.True(t, ok)
	_, want, ok := strings.Cut(clientShimSource, clientShimPackage)
	require.True(t, ok)
	assert.Contains(t, want, "//nolint:", "the source needs a directive for the linters of the CLI")
	assert.Equal(t, clientShimLint.ReplaceAllString(want, "// "), body)
	assert.NotContains(t, mf.source, "nolint", "the file of the project carries no directive")
	assert.Regexp(t, `^// Code generated by "fiber migrate"; DO NOT EDIT\.\n`, header, "linters leave a generated file alone")

	// It is Go that gofmt leaves as it is.
	formatted, err := format.Source([]byte(mf.source))
	require.NoError(t, err)
	assert.Equal(t, mf.source, string(formatted))

	file, err := parser.ParseFile(token.NewFileSet(), clientShimFile, mf.source, parser.ParseComments)
	require.NoError(t, err)
	assert.Equal(t, moduleShimPkg, file.Name.Name)
}

// clientShimDeclared parses the code the project gets and returns its imports and
// its top level declarations.
func clientShimDeclared(t *testing.T) (imports []*ast.ImportSpec, names map[string]ast.Node) {
	t.Helper()

	file, err := parser.ParseFile(token.NewFileSet(), clientShimFile, clientShimModuleFile().source, parser.SkipObjectResolution)
	require.NoError(t, err)

	names = map[string]ast.Node{}
	for _, d := range file.Decls {
		switch decl := d.(type) {
		case *ast.FuncDecl:
			if decl.Recv == nil {
				names[decl.Name.Name] = decl
			}
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					names[s.Name.Name] = s
				case *ast.ValueSpec:
					for _, id := range s.Names {
						names[id.Name] = s
					}
				}
			}
		}
	}
	return file.Imports, names
}

func Test_clientShim_NamesBelongToTheCopy(t *testing.T) {
	t.Parallel()

	imports, names := clientShimDeclared(t)
	require.NotEmpty(t, names)

	// The package is shared with the files of the other migrations: a name that is
	// not one of the v2 client's starts with agent.
	for name := range names {
		_, member := clientShimMembers[name]
		assert.True(t, member || (strings.HasPrefix(name, "agent") && !ast.IsExported(name)), "%s is a member of the v2 client or an unexported name that starts with agent", name)
	}

	// The package is shared as well, so only the standard library and fasthttp.
	for _, spec := range imports {
		path, err := strconv.Unquote(spec.Path.Value)
		require.NoError(t, err)
		first, _, _ := strings.Cut(path, "/")
		assert.True(t, !strings.Contains(first, ".") || path == "github.com/valyala/fasthttp", "%s is no dependency of the copy", path)
	}
}

func Test_clientShim_MembersAreDeclared(t *testing.T) {
	t.Parallel()

	_, names := clientShimDeclared(t)
	for member := range clientShimMembers {
		assert.Contains(t, names, member, "the copy declares %s", member)
	}

	// Every member of the removed client is either the copy's or an alias of fasthttp.
	for _, member := range clientAPIMembers {
		_, copied := clientShimMembers[member]
		assert.True(t, copied || slices.Contains(clientFasthttpAliases, member), "%s has a place to go", member)
	}
}

func Test_clientShim_CoversTheRemovedClientNames(t *testing.T) {
	t.Parallel()

	// Every member of the fiber package that Fiber v3 removed with the HTTP client
	// is either the copy's or an alias of fasthttp.
	found := 0
	for qualified, hint := range reviewAdvice {
		name, ok := strings.CutPrefix(qualified, reviewCorePath+".")
		if !ok || hint != reviewClientHint {
			continue
		}
		found++
		_, copied := clientShimMembers[name]
		assert.True(t, copied || slices.Contains(clientFasthttpAliases, name), "%s has a place to go", name)
	}
	assert.Equal(t, len(clientShimMembers)+len(clientFasthttpAliases), found)
}

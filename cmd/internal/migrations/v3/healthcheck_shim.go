// The config of the health check middleware of Fiber v2 held both probes, each with
// its endpoint, and a single `Use` answered them. Fiber v3 registers a probe on a
// route of its own, which is what the migration writes whenever it can take the
// config apart where it is declared (see MigrateHealthcheckConfig). A config it
// cannot take apart is not a value that can be split: one that several routes
// share, that a function returns or a struct keeps, that comes in as a parameter,
// that another package declares or exports, that the code completes after its
// declaration. For a module that has one, the middleware of v2 moves to the module
// package (<module>/internal/fibermigrate/health.go) and every place of the module
// that has such a value keeps using it as it was: HealthConfig and Health take the
// place of healthcheck.Config and healthcheck.New, so that the values keep meeting
// the type they were made for and the probes answer as they did.

const (
	// healthShimFile is the name of the file in the module package.
	healthShimFile = "health.go"
	// healthShimMarker is what a later run finds in the file to know that it was
	// added by a migration.
	healthShimMarker = `This file was added by "fiber migrate": the health check middleware of Fiber v2`
	// healthShimPackage is the package clause of the source, which is a package of
	// the CLI.
	healthShimPackage = "\npackage healthshim\n"
)

// healthShimHeader is what the file starts with. The code follows the package
// clause.
const healthShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + healthShimMarker + `.
// healthcheck.New of Fiber v2 answered the requests of both probes from one middleware,
// and its config held both of them. Fiber v3 registers each probe on a route of its own,
// so the code whose config could not be taken apart into two routes (a config that several
// routes share, that a function returns or a struct keeps, that is a parameter, that
// another package declares, that is completed after its declaration) uses Health and
// HealthConfig, which behave as the middleware of v2 did. Delete the file once that code
// registers one route for each probe:
// app.Get(healthcheck.LivenessEndpoint, healthcheck.New(healthcheck.Config{Probe: ...})).
`

// healthShimEmbedded is the source of the file. It is a package of the CLI, so that it
// is built, linted and tested with it.
//
//go:embed healthshim/health.go
var healthShimEmbedded string

// healthShimSource is the source with the line ends of Unix.
var healthShimSource = shimUnixLines(healthShimEmbedded)

// healthShimModuleFile is the file as it is added to the module package.
func healthShimModuleFile() moduleShimFile {
	_, body, _ := strings.Cut(healthShimSource, healthShimPackage)
	return moduleShimFile{
		name:   healthShimFile,
		marker: healthShimMarker,
		source: healthShimHeader + "\npackage " + moduleShimPkg + "\n" + body,
	}
}

// hcShim is what the project knows about the module package of one of its modules.
type hcShim struct {
	// root is the directory of the module.
	root string
	// path is the import path of the module package.
	path string
	// available is whether the module can have the file: it is in a module, and the
	// package holds nothing but files that the migrations added.
	available bool
	// needed is set while the project is planned, when a call of the middleware in
	// the module cannot be taken apart.
	needed bool
	// moved is the number of calls that were moved to the middleware of v2.
	moved int
}

// shimOf returns what the project knows about the module the file belongs to, nil
// when the file is not in one.
func (p *hcProject) shimOf(fi internal.FileInfo) *hcShim {
	dir := filepath.Dir(fi.Path)
	if s, ok := p.shims[dir]; ok {
		return s
	}

	var s *hcShim
	if mod, ok := moduleOf(fi.Path, fi.Root); ok {
		if s = p.moduleShims[mod.root]; s == nil {
			s = &hcShim{root: mod.root, path: path.Join(mod.path, moduleShimDir), available: hcShimAvailable(mod)}
			p.moduleShims[mod.root] = s
		}
	}
	p.shims[dir] = s
	return s
}

// hcShimAvailable reports whether the module package can have health.go: every Go
// file of the directory was added by a migration, and so is the file of that name
// when there is one.
func hcShimAvailable(mod goModule) bool {
	dir := filepath.Join(mod.root, filepath.FromSlash(moduleShimDir))
	if !moduleShimDirIsOurs(dir) {
		return false
	}

	data, err := os.ReadFile(filepath.Join(dir, healthShimFile)) // #nosec G304 -- next to the files of the project being migrated
	if err != nil {
		return os.IsNotExist(err)
	}
	return bytes.Contains(data, []byte(healthShimMarker))
}

// hcShimFile is the middleware of v2 as one file of the project uses it.
type hcShimFile struct {
	// module is what the project knows about the module package.
	module *hcShim
	// name is what the file calls the module package, path its import path.
	name string
	path string
	// add is whether the file has to import the package.
	add bool
	// used is set when an edit refers to the package.
	used bool
}

// openShim prepares the file to use the middleware of v2 that the module package
// holds, in the pass that writes and for a module that needs it: the module
// package gets the file, and the places of the file that mention the config of v2
// are moved to it.
func (h *hcMigration) openShim() {
	if h.proj.planning {
		return
	}
	s := h.proj.shimOf(h.fi)
	if s == nil || !s.needed || !s.available {
		return
	}

	importPath, ok := ensureModuleShim(h.fi, healthShimModuleFile())
	if !ok {
		return
	}
	name, add := mw1ImportName(h.g.src, importPath, moduleShimPkg)
	if add && mw1UsesName(h.g.file, name) {
		return // the file uses the name for something else
	}
	h.shim = &hcShimFile{module: s, name: name, path: importPath, add: add}
	h.collectMentions()
}

// hcV2Fields are the fields of healthcheck.Config in v2; v3 has Next and Probe.
var hcV2Fields = append(slices.Clone(hcV2OnlyFields), hcNext)

// hasV2Config reports whether an argument of the call is a config literal that has a
// field only v2 has.
func (h *hcMigration) hasV2Config(call *ast.CallExpr) bool {
	for _, arg := range call.Args {
		if lit, ok := mw1ConfigLit(arg, h.names); ok && hasV2OnlyField(lit) {
			return true
		}
	}
	return false
}

// hasV3Config reports whether an argument of the call is a config literal with a
// field that v2 does not have: the code was written for v3 already.
func (h *hcMigration) hasV3Config(call *ast.CallExpr) bool {
	for _, arg := range call.Args {
		if lit, ok := mw1ConfigLit(arg, h.names); ok && hasV3Field(lit) {
			return true
		}
	}
	return false
}

// hasV3Field reports whether the literal sets a field that healthcheck.Config of v2
// does not have.
func hasV3Field(lit *ast.CompositeLit) bool {
	for _, elt := range lit.Elts {
		kv, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		if id, isIdent := kv.Key.(*ast.Ident); isIdent && !slices.Contains(hcV2Fields, id.Name) {
			return true
		}
	}
	return false
}

// inRoute reports whether the call is the handler of a route, as in
// app.Get(path, healthcheck.New()), which is how v3 registers a probe.
func (*hcMigration) inRoute(call *ast.CallExpr, stack []ast.Node) bool {
	if len(stack) == 0 {
		return false
	}
	parent, ok := stack[len(stack)-1].(*ast.CallExpr)
	if !ok {
		return false
	}
	sel, isSel := parent.Fun.(*ast.SelectorExpr)
	return isSel && slices.Contains(routeMethods, sel.Sel.Name) && len(parent.Args) > 1 && parent.Args[0] != ast.Expr(call)
}

// useShim keeps the calls on the middleware of Fiber v2 that the module package
// holds, when the module can have it, and reports whether it did. While the project
// is planned it only remembers that the module needs the file.
func (h *hcMigration) useShim(calls []*ast.CallExpr, stack []ast.Node, why string) bool {
	if h.proj.planning {
		if s := h.proj.shimOf(h.fi); s != nil && s.available {
			s.needed = true
			return true
		}
		return false
	}
	if h.shim == nil {
		return false
	}

	for _, call := range calls {
		h.moveToShim(call, stack, why)
	}
	return true
}

// refuse deals with a call of healthcheck.New that cannot be taken apart into the
// routes of v3: it moves to the middleware of v2 in the module package, or stays and
// is reported.
func (h *hcMigration) refuse(call *ast.CallExpr, stack []ast.Node, why string) {
	if !h.useShim([]*ast.CallExpr{call}, stack, why) {
		h.reportUnmigrated(call, why)
	}
}

// hcByHand ends the reasons that tell what the user has to do when a call stays.
const hcByHand = " and has to be split by hand"

// moveToShim replaces healthcheck.New of the call with Health of the module package
// and says why.
func (h *hcMigration) moveToShim(call *ast.CallExpr, stack []ast.Node, why string) {
	callee := hcCallee(call)
	if callee == nil {
		return
	}
	if importsShadowed(h.shim.name, callee.Pos(), stack) {
		h.rep.notef(call, "%s.New() was left as it is: %s. A variable called %s hides the package %s that holds the middleware of v2 here, "+
			"so register one route per probe, app.Get(%s.LivenessEndpoint, %s.New(...)) and app.Get(%s.ReadinessEndpoint, %s.New(...))",
			h.names[0], strings.TrimSuffix(why, hcByHand), h.shim.name, h.shim.path, h.names[0], h.names[0], h.names[0], h.names[0])
		return
	}

	h.edits.replaceNode(h.g, callee, h.shim.name+".Health")
	h.shim.used = true
	h.shim.module.moved++
}

// hcCallee returns the selector healthcheck.New that a call calls.
func hcCallee(call *ast.CallExpr) *ast.SelectorExpr {
	fun := call.Fun
	for {
		p, ok := fun.(*ast.ParenExpr)
		if !ok {
			break
		}
		fun = p.X
	}
	sel, ok := fun.(*ast.SelectorExpr)
	if !ok {
		return nil
	}
	return sel
}

// collectMentions schedules the edits that move the places of the file that name
// the config of v2, or its default, to the module package, so that the values the
// middleware of v2 there takes are of the type it declares. A probe in the form of
// v3, and a literal with a field that only v3 has, are left as they are, and so is
// the type that a declaration split into two configs names.
func (h *hcMigration) collectMentions() {
	keep := map[ast.Node]bool{}
	h.g.walk(func(n ast.Node, stack []ast.Node) bool {
		switch x := n.(type) {
		case *ast.CallExpr:
			if _, isNew := h.isNewCall(x); isNew && h.inRoute(x, stack) && !h.hasV2Config(x) {
				return false
			}
		case *ast.CompositeLit:
			if lit, isConfig := mw1ConfigLit(x, h.names); isConfig && hasV3Field(lit) {
				keep[lit.Type] = true
			}
		case *ast.SelectorExpr:
			h.mention(x, stack, keep)
		}
		return true
	})
}

// mention schedules the edit of one selector, if it names a member of the healthcheck
// package that has a counterpart in the module package.
func (h *hcMigration) mention(sel *ast.SelectorExpr, stack []ast.Node, keep map[ast.Node]bool) {
	var counterpart string
	switch {
	case mw1IsMember(sel, h.names, "Config"):
		if keep[sel] {
			return
		}
		if h.isEmbedded(sel, stack) {
			h.rep.notef(sel, "the embedded field %s.Config is called HealthConfig now, as the type of the middleware of Fiber v2 that this module keeps in %s/%s is: "+
				"rename its uses, x.Config becomes x.HealthConfig and Config: becomes HealthConfig: in the literals of the struct",
				h.names[0], moduleShimDir, healthShimFile)
		}
		counterpart = "HealthConfig"
	case mw1IsMember(sel, h.names, "ConfigDefault"):
		counterpart = "HealthConfigDefault"
	case mw1IsMember(sel, h.names, "New") && !hcIsCallee(sel, stack):
		counterpart = "Health"
	default:
		return
	}

	if importsShadowed(h.shim.name, sel.Pos(), stack) {
		h.rep.notef(sel, "%s.%s was left as it is: a variable called %s hides the package %s that holds the middleware of Fiber v2 here",
			h.names[0], sel.Sel.Name, h.shim.name, h.shim.path)
		return
	}
	h.renames.replaceNode(h.g, sel, h.shim.name+"."+counterpart)
	h.shim.used = true
	if counterpart == "Health" {
		h.shim.module.moved++
	}
}

// hcIsCallee reports whether the selector is what a call calls.
func hcIsCallee(sel *ast.SelectorExpr, stack []ast.Node) bool {
	for _, node := range slices.Backward(stack) {
		switch p := node.(type) {
		case *ast.ParenExpr:
			continue
		case *ast.CallExpr:
			return hcCallee(p) == sel
		}
		return false
	}
	return false
}

// isEmbedded reports whether the selector is the type of an embedded field of a
// struct, which a type of another name would rename.
func (*hcMigration) isEmbedded(sel *ast.SelectorExpr, stack []ast.Node) bool {
	i := len(stack) - 1
	if i >= 0 {
		if star, ok := stack[i].(*ast.StarExpr); ok && star.X == ast.Expr(sel) {
			i--
		}
	}
	if i < 1 {
		return false
	}

	field, isField := stack[i].(*ast.Field)
	if !isField || len(field.Names) > 0 {
		return false
	}
	_, inStruct := stack[i-1].(*ast.FieldList)
	if !inStruct || i < 2 {
		return false
	}
	_, isStruct := stack[i-2].(*ast.StructType)
	return isStruct
}

// dropRename forgets the edit that was scheduled for the node, because the node is
// kept as it is.
func (h *hcMigration) dropRename(n ast.Node) {
	start, end := h.g.offset(n.Pos()), h.g.offset(n.End())
	h.renames.edits = slices.DeleteFunc(h.renames.edits, func(e textEdit) bool { return e.start == start && e.end == end })
}

// reportShims leaves one note for each module package that holds the middleware of
// v2 for calls of the module, on the file that holds it. The calls are exact, as they
// answer the probes as before, so they have no notes of their own.
func (p *hcProject) reportShims() {
	for _, root := range slices.Sorted(maps.Keys(p.moduleShims)) {
		s := p.moduleShims[root]
		if s.moved == 0 {
			continue
		}
		rel, err := filepath.Rel(p.root, filepath.Join(s.root, filepath.FromSlash(moduleShimDir), healthShimFile))
		if err != nil {
			continue
		}
		internal.Notef(internal.FileInfo{Root: p.root, Rel: rel}, 1,
			"the health check middleware of Fiber v2 is kept in this file for %d %s in the module whose config cannot be taken apart into one route for each probe, "+
				"as v3 wants (a config that several routes share, that a function returns or a struct keeps, that is a parameter, that another package declares, "+
				"that is completed after its declaration; a group; a handler kept in a variable): they call Health, use HealthConfig and answer as they did. "+
				"Where a probe can be registered on a route of its own, app.Get(healthcheck.LivenessEndpoint, healthcheck.New(healthcheck.Config{Probe: ...})), "+
				"do that and delete this file when nothing uses it",
			s.moved, hcCalls(s.moved))
	}
}

// hcCalls counts calls.
func hcCalls(n int) string {
	if n == 1 {
		return "call of healthcheck.New"
	}
	return "calls of healthcheck.New"
}

// hcUsesQualifier reports whether the source has a selector on the identifier name,
// that is whether an edit that was meant to write it was not dropped.
func hcUsesQualifier(src, name string) bool {
	g, ok := parseSource(src)
	return ok && contribSelectorBases(g)[name]
}

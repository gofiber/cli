func Test_MigrateHealthcheckConfig_ShimNeedsAFileThatCanBeRead(t *testing.T) {
	t.Parallel()

	// a configuration that is declared in a file of the package that does not parse
	// cannot be followed, and the call stays where it is
	res := mw1RunModule(t, v3.MigrateHealthcheckConfig, map[string]string{
		"main.go": hcShimMain(``, `	app.Use(healthcheck.New(declared))
`),
		"broken.go": "package main\n\nvar declared = healthcheck.Config{\n",
	})

	assert.Contains(t, res.file(), "app.Use(healthcheck.New(declared))")
	assert.Empty(t, res.added)
	if assert.Len(t, res.notes, 1) {
		assert.Contains(t, res.notes[0], "a file of its package cannot be read")
	}
}

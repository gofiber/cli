// hcShimFile is where the module package keeps the middleware of Fiber v2.
const hcShimFile = "internal/fibermigrate/health.go"

// hcShimImport is the import of the module package.
const hcShimImport = `"example.com/app/internal/fibermigrate"`

// hcShimMain wraps the body of main for a project that imports Fiber v2 and its
// healthcheck middleware.
func hcShimMain(decls, body string) string {
	decls = strings.Trim(decls, "\n")
	if decls != "" {
		decls += "\n\n"
	}
	return "package main\n\n" + hcImports + "\n" + decls + "func main() {\n\tapp := fiber.New()\n" + body + "}\n"
}

// hcShimAgain runs the migration over what a first run produced and checks that it
// changes nothing and says nothing.
func hcShimAgain(t *testing.T, first mw1Module) {
	t.Helper()

	files := maps.Clone(first.files)
	maps.Copy(files, first.added)
	second := mw1RunModule(t, v3.MigrateHealthcheckConfig, files)

	assert.Empty(t, second.stdout)
	assert.Empty(t, second.notes)
	assert.Empty(t, second.added)
	assert.Equal(t, files, second.files)
}

func Test_MigrateHealthcheckConfig_ShimAddsTheMiddlewareOfV2(t *testing.T) {
	t.Parallel()

	res := mw1RunModule(t, v3.MigrateHealthcheckConfig, map[string]string{"main.go": hcShimMain(`
var shared = healthcheck.Config{
	LivenessProbe:  func(c *fiber.Ctx) bool { return true },
	ReadinessProbe: func(c *fiber.Ctx) bool { return false },
}
`, `	app.Use(healthcheck.New(shared))
	app.Use("/api", healthcheck.New(shared))
`)})

	file := res.file()
	assert.Contains(t, file, "var shared = fibermigrate.HealthConfig{")
	assert.Contains(t, file, "\tapp.Use(fibermigrate.Health(shared))\n")
	assert.Contains(t, file, "\tapp.Use(\"/api\", fibermigrate.Health(shared))\n")
	assert.Contains(t, file, hcShimImport)
	assert.NotContains(t, file, "healthcheck", "nothing of the file uses the middleware of v3 any more")
	assert.Equal(t, "Migrating healthcheck middleware configs\n", res.stdout)

	shim := res.added[hcShimFile]
	require.NotEmpty(t, shim)
	assert.True(t, strings.HasPrefix(shim, "// Code generated by \"fiber migrate\"; DO NOT EDIT.\n"))
	assert.Contains(t, shim, `This file was added by "fiber migrate"`)
	assert.Contains(t, shim, "\npackage fibermigrate\n")
	assert.Contains(t, shim, "func Health(config ...HealthConfig) fiber.Handler {")
	formatted, err := format.Source([]byte(shim))
	require.NoError(t, err)
	assert.Equal(t, shim, string(formatted), "the file is formatted")
	assert.Len(t, res.added, 1)

	// the places are exact, so one note on the file that holds the middleware is all
	if assert.Len(t, res.notes, 1) {
		assert.Contains(t, res.notes[0], "internal/fibermigrate/health.go:1: the health check middleware of Fiber v2 is kept in this file for 2 calls of healthcheck.New in the module")
		assert.Contains(t, res.notes[0], "delete this file")
	}

	hcShimAgain(t, res)
}


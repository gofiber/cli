func Test_MigrateHealthcheckConfig_ShimIsNotAddedToAPackageThatIsNotOurs(t *testing.T) {
	t.Parallel()

	src := hcShimMain(`
var shared = healthcheck.Config{LivenessEndpoint: "/up"}
`, `	app.Use(healthcheck.New(shared))
	app.Use("/x", healthcheck.New(shared))
`)
	foreign := "package fibermigrate\n\nfunc Mine() {}\n"
	res := mw1RunModule(t, v3.MigrateHealthcheckConfig, map[string]string{"main.go": src, "internal/fibermigrate/mine.go": foreign})

	assert.Equal(t, src, res.file())
	assert.Equal(t, foreign, res.files["internal/fibermigrate/mine.go"])
	assert.Empty(t, res.added)
	assert.Len(t, res.notes, 3)

	// and a health.go that a migration did not write is not replaced
	mine := "// Code generated by \"fiber migrate\"; DO NOT EDIT.\n// This file was added by \"fiber migrate\": something else.\npackage fibermigrate\n"
	res = mw1RunModule(t, v3.MigrateHealthcheckConfig, map[string]string{"main.go": src, "internal/fibermigrate/health.go": mine})
	assert.Equal(t, src, res.file())
	assert.Equal(t, mine, res.files["internal/fibermigrate/health.go"])
	assert.Len(t, res.notes, 3)
}


// The package of the shims holds code that is not ours: the type cannot be added,
// and the program is told.
func Test_MigrateSessionSource_NoPlaceForTheType(t *testing.T) {
	t.Parallel()

	src := `package main

import "github.com/gofiber/fiber/v2/middleware/session"

func is(v any) bool {
	switch v.(type) {
	case session.Source:
		return true
	case string:
		return false
	}
	return false
}
`
	res := mw3RunModule(t, map[string]string{
		"main.go":                       src,
		"internal/fibermigrate/mine.go": "package fibermigrate\n\nvar Mine = 1\n",
	}, v3.MigrateSessionExtractor)

	assert.Contains(t, res.files["main.go"], "\tcase session.Source:\n")
	assert.NotContains(t, res.files, mw3ShimPath)
	msgs := mw3Messages(res.notes)
	require.NotEmpty(t, msgs)
	assert.Contains(t, msgs[0], "internal/fibermigrate holds code that is not from \"fiber migrate\"")

	// Without a module there is nowhere to put it either.
	plain, plainRes := mw3RunOne(t, src, v3.MigrateSessionExtractor)
	assert.Contains(t, plain, "\tcase session.Source:\n")
	assert.NotEmpty(t, plainRes.notes)
}

// The import of the package is aliased when its name is taken, and the session
// package may have a name of its own.
func Test_MigrateSessionSource_NamesOfTheImports(t *testing.T) {
	t.Parallel()

	res := mw3RunModule(t, map[string]string{
		"main.go": `package main

import (
	sess "github.com/gofiber/fiber/v2/middleware/session"
)

var fibermigrate = "taken"

func is(v any) (sess.Source, bool) {
	s, ok := v.(sess.Source)
	return s, ok && fibermigrate != ""
}
`,
	}, v3.MigrateSessionExtractor)

	got := res.files["main.go"]
	assert.Contains(t, got, "fibermigrate2 \"example.com/app/internal/fibermigrate\"")
	assert.Contains(t, got, "func is(v any) (fibermigrate2.SessionSource, bool) {")
	assert.Contains(t, got, "s, ok := v.(fibermigrate2.SessionSource)")
	assert.NotContains(t, got, "middleware/session")
}

// A module of the project in a directory below the one the command runs in has
// its own package for the type.
func Test_MigrateSessionSource_EachModuleHasItsOwn(t *testing.T) {
	t.Parallel()

	res := mw3Run(t, map[string]string{
		"go.mod": "module example.com/app\n\ngo 1.25\n",
		"main.go": `package main

import "github.com/gofiber/fiber/v2/middleware/session"

func where() session.Source { return session.SourceHeader }
`,
		"tools/go.mod": "module example.com/tools\n\ngo 1.25\n",
		"tools/tool.go": `package tools

import "github.com/gofiber/fiber/v2/middleware/session"

func is(v any) bool {
	_, ok := v.(session.Source)
	return ok
}
`,
	}, v3.MigrateSessionExtractor)

	assert.Contains(t, res.files["main.go"], "func where() string { return \"header\" }")
	assert.Contains(t, res.files["tools/tool.go"], "v.(fibermigrate.SessionSource)")
	assert.Contains(t, res.files["tools/tool.go"], "\"example.com/tools/internal/fibermigrate\"")
	assert.NotContains(t, res.files, mw3ShimPath)
	assert.Contains(t, res.files, "tools/"+mw3ShimPath)
}

// The embedded field keeps its name with the type of the module, too.
func Test_MigrateSessionSource_EmbeddedFieldOfTheType(t *testing.T) {
	t.Parallel()

	res := mw3RunModule(t, map[string]string{
		"main.go": `package main

import "github.com/gofiber/fiber/v2/middleware/session"

type lookup struct {
	session.Source
}

type pointer struct {
	*session.Source ` + "`json:\"s\"`" + `
}

func is(v any) bool {
	_, ok := v.(session.Source)
	return ok
}
`,
	}, v3.MigrateSessionExtractor)

	got := res.files["main.go"]
	assert.Contains(t, got, "type lookup struct {\n\tSource fibermigrate.SessionSource\n}")
	assert.Contains(t, got, "\tSource *fibermigrate.SessionSource `json:\"s\"`\n")
}

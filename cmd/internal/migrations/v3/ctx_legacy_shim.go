package v3

import (
	"strings"

	_ "embed" // the source of the file that gives the context the methods of Fiber v2

	"github.com/gofiber/cli/cmd/internal"
)

// An interface of the project can mirror the context of Fiber v2: it declares methods of
// *fiber.Ctx (ParamsInt, QueryInt, BodyParser, UserContext, ...), a handler asks for it
// instead of the context so that a test can hand it a fake, and the code that calls the
// handler hands it the context, which implemented the interface without saying so. The
// Ctx of Fiber v3 does not have the methods v3 removed, so it no longer does. For the
// interfaces whose methods are all methods that v3 removed or kept, the migration wraps
// the context in the LegacyCtx of the module package (<module>/internal/fibermigrate/ctx.go),
// a fiber.Ctx that has the removed methods and behaves as they did in v2. Its source is
// ctxshim/ctx.go.
const (
	// legacyShimFile is the name of the file in the module package.
	legacyShimFile = "ctx.go"
	// legacyShimMarker is what a later run finds in the file to know that it was added by a
	// migration.
	legacyShimMarker = `This file was added by "fiber migrate": the methods of the context of Fiber v2 that v3 removed`
	// legacyShimPackage is the package clause of the source, which is a package of the CLI.
	legacyShimPackage = "\npackage ctxshim\n"
	// legacyShimType is the type of the module package that wraps the context.
	legacyShimType = "LegacyCtx"
	// legacyShimAlias is the name of the second import of the module package, for a file in
	// which fibermigrate means something else.
	legacyShimAlias = "fibermigratectx"
)

// legacyShimHeader is what the file starts with. The code follows the package clause.
const legacyShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + legacyShimMarker + `.
// An interface of this module declares methods of the context of Fiber v2 (ParamsInt, QueryInt,
// BodyParser, UserContext, ...) and the code hands a fiber.Ctx to it. The Ctx of Fiber v3 does
// not have the methods v3 removed, so it would not implement the interface: LegacyCtx is a
// fiber.Ctx that does, with the behavior those methods had in v2. Delete the file once the
// interface asks for what v3 has: fiber.Params[int](c, key), fiber.Query[int](c, key),
// c.Bind().Body(&v), c.Context().
`

//go:embed ctxshim/ctx.go
var legacyShimEmbedded string

// legacyShimSource is the source with the line ends of Unix.
var legacyShimSource = shimUnixLines(legacyShimEmbedded)

// legacyShimModuleFile is the file as it is added to the module package.
func legacyShimModuleFile() moduleShimFile {
	_, body, _ := strings.Cut(legacyShimSource, legacyShimPackage)
	return moduleShimFile{
		name:   legacyShimFile,
		marker: legacyShimMarker,
		source: legacyShimHeader + "\npackage " + moduleShimPkg + "\n" + body,
	}
}

// legacyShim is what a file knows about the LegacyCtx of the package of its module.
type legacyShim struct {
	// path is the import path of the module package.
	path string
	fi   internal.FileInfo
	// tried says the module was asked for the file, ok that it has it.
	tried, ok bool
}

// available makes sure the module of the file has the file, adding it on first use, and
// reports whether it does.
func (s *legacyShim) available() bool {
	if !s.tried {
		s.tried = true
		s.path, s.ok = ensureModuleShim(s.fi, legacyShimModuleFile())
	}
	return s.ok
}

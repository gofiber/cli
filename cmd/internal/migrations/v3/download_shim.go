// Ctx.Download of Fiber v2 sent the file with its byte ranges, as every file the context
// sent. Fiber v3 sends the file of Ctx.Download without them and has no setting to ask
// for them, so a call is not migrated to a call of Ctx.Download of v3. The nearest
// calls of v3 are c.Attachment(name) and c.SendFile(path, fiber.SendFile{ByteRange: true}),
// but Attachment also sets the Content-Type from the extension of the name, and SendFile
// leaves a type that is set alone: a JSON file downloaded as export.csv would be a CSV
// file, one called x.json would get a charset the v2 response did not have, and a type
// that the handler chose would be lost. The migration calls Download of the module
// package instead (<module>/internal/fibermigrate/download.go), which is Ctx.Download of v3
// with the ranges, and leaves the type as it was. Its source is downloadshim/download.go.
const (
	// downloadShimFile is the name of the file in the module package.
	downloadShimFile = "download.go"
	// downloadShimMarker is what a later run finds in the file to know that it was added
	// by a migration.
	downloadShimMarker = `This file was added by "fiber migrate": Download with the byte ranges of Fiber v2`
	// downloadShimPackage is the package clause of the source, which is a package of the
	// CLI.
	downloadShimPackage = "\npackage downloadshim\n"
	// downloadShimAlias is the name of the second import of the module package, for a
	// file in which fibermigrate means something else.
	downloadShimAlias = "fibermigrateshim"
)

// downloadShimHeader is what the file starts with. The code follows the package clause.
const downloadShimHeader = `// Code generated by "fiber migrate"; DO NOT EDIT.

// ` + downloadShimMarker + `.
// Ctx.Download of Fiber v2 sent the file with its byte ranges: a request for a part of it (a
// resumed download, the seeking of a player) got that part. Ctx.Download of Fiber v3 sends the
// whole file and has no setting to ask for the ranges. Download is Ctx.Download of v3 with
// them, and it leaves the Content-Type of the response as it was, for SendFile to give it the
// type of the file. Delete the file once the code calls c.Attachment(name) and
// c.SendFile(path, fiber.SendFile{ByteRange: true}) itself, and set the type it needs: Attachment
// sets the Content-Type from the extension of the name, and SendFile keeps a type that is set.
`

//go:embed downloadshim/download.go
var downloadShimSource string

// downloadShimModuleFile is the file as it is added to the module package.
func downloadShimModuleFile() moduleShimFile {
	_, body, _ := strings.Cut(downloadShimSource, downloadShimPackage)
	return moduleShimFile{
		name:   downloadShimFile,
		marker: downloadShimMarker,
		source: downloadShimHeader + "\npackage " + moduleShimPkg + "\n" + body,
	}
}

// downloadShim is what a file knows about the Download of the package of its module.
type downloadShim struct {
	fi internal.FileInfo
	// path is the import path of the module package.
	path string
	// tried says the module was asked for the file, ok that it has it.
	tried, ok bool
}

// available makes sure the module of the file has the Download, adding it on first use,
// and reports whether it does. A file outside of a module, or a package that holds code
// the migrations did not write, cannot have it.
func (d *downloadShim) available() bool {
	if !d.tried {
		d.tried = true
		d.path, d.ok = ensureModuleShim(d.fi, downloadShimModuleFile())
	}
	return d.ok
}

// moduleDownload reports whether sel is the Download of the module package: the
// function a migrated Ctx.Download became.
func (rf *reviewFile) moduleDownload(sel *ast.SelectorExpr) bool {
	id, ok := sel.X.(*ast.Ident)
	if !ok || sel.Sel.Name != ctxDownload {
		return false
	}
	return slices.ContainsFunc(rf.g.file.Imports, func(spec *ast.ImportSpec) bool {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil || !strings.HasSuffix(importPath, "/"+moduleShimDir) {
			return false
		}
		return pkgImportName(spec) == id.Name
	})
}

// sendsDynamicFile reports whether the call sends a file by a name that is not a
// literal: SendFile or Download of a context, or the Download of the module package,
// which takes the context before the file.
func (rf *reviewFile) sendsDynamicFile(call *ast.CallExpr, sel *ast.SelectorExpr, stack []ast.Node) bool {
	if rf.moduleDownload(sel) {
		return len(call.Args) > 1 && !isStringLiteral(call.Args[1])
	}
	return len(call.Args) > 0 && !isStringLiteral(call.Args[0]) && rf.isCtxMethod(sel, stack)
}

// pkgImportName returns the name an import binds: its alias, or else the last
// element of its path.
func pkgImportName(spec *ast.ImportSpec) string {
	if spec.Name != nil {
		return spec.Name.Name
	}
	importPath, err := strconv.Unquote(spec.Path.Value)
	if err != nil {
		return ""
	}
	return defaultImportName(importPath)
}

// The registry carries the listener settings of a fiber.Config that cannot move to
// the call that starts the app, because the code that sets them is not the call,
// nor in its reach: a condition, a value that a function only knows, an app that
// another function or another package starts. The settings travel with the app
// instead, and since the app can cross packages, the registry is one for the whole
// module: <module>/internal/fibermigrate/listen.go (see module_shim.go).
//
// In the migrated code a fiber.ListenConfig variable sits next to the fiber.Config
// variable and takes over its settings, fiber.New(cfg) becomes
// fibermigrate.NewApp(cfg, cfgListen), which records the settings for the app, and
// the calls that can start such an app, in any package of the module and also in a
// file that does not import fiber, ask for them:
//
//	app.Listen(addr, fibermigrate.ListenConfig(app))
//
// A function that returns the config (see app_listen_returned.go) returns the
// registry's Config instead, the config of v2 with the four settings, and the
// fiber.New calls that make apps from its result become fibermigrate.New. The code
// that reads the settings from app.Config() reads them from fibermigrate.ConfigOf(app)
// (see app_listen_reads.go).
//
// The source of the registry is a package of its own, listenshim, which is built and
// tested like any other.

//go:embed listenshim/listen.go
var appShimEmbedded string

const (
	// appShimFile is the file of the registry in the package of the module.
	appShimFile = "listen.go"
	// appShimMarker is the sentence of the source that tells a later run that the file
	// is the registry.
	appShimMarker = moduleShimMarker + ": the listener settings of an app"
	// appShimPackage is the package clause of the source.
	appShimPackage = "package listenshim"
	// appShimHeader is what every file of the package starts with.
	appShimHeader = "// Code generated by \"fiber migrate\"; DO NOT EDIT.\n\n"

	// The names the registry exports.
	appShimNew          = "NewApp"
	appShimConfig       = "ListenConfig"
	appShimListen       = "Listen"
	appShimListener     = "Listener"
	appShimListenFunc   = "ListenFunc"
	appShimListenerFunc = "ListenerFunc"
	appShimConfigType   = "Config"
	appShimNewV2        = "New"
	appShimConfigOf     = "ConfigOf"

	// appMainPackage is the name of a package that nothing imports.
	appMainPackage = "main"
)

// appShimModuleFile is the file of the registry the way a module gets it.
func appShimModuleFile() moduleShimFile {
	return moduleShimFile{
		name:   appShimFile,
		marker: appShimMarker,
		source: appShimHeader + strings.Replace(appShimEmbedded, appShimPackage, "package "+moduleShimPkg, 1),
	}
}

// isShimFile reports whether the file is one of the package the migrations add to
// the module, which they never read as the project's own code.
func isShimFile(path, content string) bool {
	return filepath.Base(filepath.Dir(path)) == moduleShimPkg && strings.Contains(content, moduleShimMarker)
}

// appShimModule is the registry of one module of the project, as the planner
// sees it.
type appShimModule struct {
	// seen are the calls and method values already planned.
	seen map[ast.Node]bool
	// first is the first app the module makes with the registry, where its note goes.
	first *appNew
	// root is the directory of the go.mod of the module.
	root string
	// path is the import path of the package of the registry.
	path string
	// exposed are the exported names of packages that other modules can import,
	// which the apps of the registry leave the module through.
	exposed []string
	// configs are the functions that return a fibermigrate.Config now, and
	// exposedConfigs those of them that other modules can call.
	configs        []string
	exposedConfigs []string
	// takes are the functions that take one, holds the variables and fields that hold
	// one, and exposedTypes those of them that other modules can use.
	takes        []string
	holds        []string
	exposedTypes []string
	// starts are the calls that ask the registry for the settings.
	starts []*appStartInfo
	// values are the methods that start an app, used as values.
	values []*appValueInfo
	// fi is a file of the module, which the registry is added through.
	fi internal.FileInfo
	// checked and available say whether the package could be added, once that was asked.
	checked   bool
	available bool
}

// shimOf returns the registry of the module of the file.
func (pl *appPlanner) shimOf(mod goModule, fi internal.FileInfo) *appShimModule {
	if sp := pl.shims[mod.root]; sp != nil {
		return sp
	}
	path, _ := moduleShimPath(fi)
	sp := &appShimModule{root: mod.root, path: path, fi: fi, seen: map[ast.Node]bool{}}
	pl.shims[mod.root] = sp
	return sp
}

// ensure makes sure the module has the registry, adding it on first use.
func (sp *appShimModule) ensure() bool {
	if !sp.checked {
		sp.checked = true
		_, sp.available = ensureModuleShim(sp.fi, appShimModuleFile())
	}
	return sp.available
}

// moduleOf finds the module of the file, once per directory.
func (pl *appPlanner) moduleOf(f *appFile) (goModule, bool) {
	dir := filepath.Dir(f.path)
	if m, seen := pl.mods[dir]; seen {
		return m.mod, m.ok
	}
	mod, ok := moduleOf(f.path, pl.root)
	pl.mods[dir] = appModuleOf{mod: mod, ok: ok}
	return mod, ok
}

// appModuleOf is the answer of moduleOf for a directory.
type appModuleOf struct {
	mod goModule
	ok  bool
}

// appShimRefusal says why the registry cannot carry the settings of a source. The
// user is told about the reasons that are not obvious from the code.
type appShimRefusal struct {
	why  string
	tell bool
	// nobody is set when no call of the module starts the app, so that the settings
	// have no effect and can be dropped.
	nobody bool
	// flow is set when the reason is the one of the places the config goes to (see
	// app_listen_flow.go), which says more than why the config is not handed
	// straight to fiber.New.
	flow bool
}

// carry plans to keep the settings of the source with the apps it creates: every
// setting, whether it could move or not, so that the code reads one way.
//
// It returns the function that adds the work to the plan, or why it cannot be done.
// The configs a function returns are carried together, whichever of them asks first.
func (pl *appPlanner) carry(src *appListenSource) (commit func(), refusal appShimRefusal) {
	if src.retFn == nil {
		return pl.carrySource(src)
	}

	if done := pl.returned[src.retFn]; done != nil {
		return done.commit, done.refusal
	}
	work, why := pl.carrySource(src)
	done := &appReturned{refusal: why}
	if work != nil {
		applied := false
		done.commit = func() {
			if !applied {
				applied = true
				work()
			}
		}
	}
	pl.returned[src.retFn] = done
	return done.commit, done.refusal
}

// appReturned is the outcome of carrying the configs that a function returns.
type appReturned struct {
	commit  func()
	refusal appShimRefusal
}

func (pl *appPlanner) carrySource(src *appListenSource) (commit func(), refusal appShimRefusal) {
	quiet := func(why string) (func(), appShimRefusal) { return nil, appShimRefusal{why: why} }
	tell := func(why string) (func(), appShimRefusal) { return nil, appShimRefusal{why: why, tell: true} }

	// a config that is not handed straight to fiber.New is followed to the places it
	// goes to (see app_listen_flow.go)
	if src.escapes || len(src.creations) == 0 || (src.retFn == nil && src.node == nil && (src.lit == nil || len(src.creations) != 1)) {
		return pl.carryFlow(src)
	}

	f := src.file
	mod, inModule := pl.moduleOf(f)
	switch {
	case !f.walked:
		return quiet("the file is not part of the migration")
	case !inModule:
		return tell("the file is not in a module, and the registry is a package of the module")
	case src.node != nil && src.scope == nil && f.ix.pkgOf(f).name != appMainPackage && appIsExported(src.name):
		return tell(src.name + " is an exported variable, which other packages can create apps with")
	}
	for _, c := range src.creations {
		cm, ok := pl.moduleOf(c.file)
		switch {
		case ok && cm.root != mod.root:
			return tell(fmt.Sprintf("the config is made in %s and the app in %s, which belong to different Go modules: "+
				"each module gets a registry of its own, and two of them cannot exchange values", appFileLabel(f), appFileLabel(c.file)))
		case !ok || !c.file.walked:
			return quiet("the app is created in a file that is not part of this module or the migration")
		}
	}

	sp := pl.shimOf(mod, f.fi)
	if sp.path == "" {
		return tell("the file is not in a module, and the registry is a package of the module")
	}
	wrap, values, refusal := pl.shimStarts(pl.returnedSource(src), mod)
	if refusal.why != "" {
		return nil, refusal
	}

	w := newShimWork(pl, sp.path)
	var why string
	switch {
	case src.retFn != nil:
		why = shimReturned(w, src)
	case src.node != nil:
		why = src.shimVariable(w)
	default:
		why = src.shimLiteral(w)
	}
	if why != "" {
		return tell(why)
	}

	for _, s := range wrap {
		if rw := s.rewriteShim(appImports{}, "", sp.path); rw.problem != "" {
			return tell(fmt.Sprintf("the call at line %d cannot ask for them: %s", s.file.g.line(s.call.Pos()), rw.problem))
		}
	}
	if !sp.ensure() {
		return tell("the directory " + moduleShimDir + " holds a Go file that is not the registry's")
	}

	exposed := pl.exposure(mod, src.creations)
	returned := pl.returnedLabels(mod, src)
	return func() {
		w.commit()
		for _, sel := range src.sels {
			pl.followed[sel] = true
		}
		for _, s := range wrap {
			if !sp.seen[s.call] {
				sp.seen[s.call] = true
				sp.starts = append(sp.starts, s)
			}
		}
		for _, v := range values {
			if !sp.seen[v.sel] {
				sp.seen[v.sel] = true
				sp.values = append(sp.values, v)
			}
		}
		for _, name := range exposed {
			if !slices.Contains(sp.exposed, name) {
				sp.exposed = append(sp.exposed, name)
			}
		}
		if returned.name != "" && !slices.Contains(sp.configs, returned.name) {
			sp.configs = append(sp.configs, returned.name)
		}
		if returned.exposed && !slices.Contains(sp.exposedConfigs, returned.name) {
			sp.exposedConfigs = append(sp.exposedConfigs, returned.name)
		}
		if sp.first == nil {
			sp.first = &src.creations[0]
		}
	}, appShimRefusal{}
}

// shimStarts finds the calls that can start the apps of the source and take their
// settings from the registry: those that start them, and every call of the module
// whose app cannot be traced, which may be one of them. It fails when a call of
// another module starts one of the apps, which the registry of this module cannot
// reach, and when the code uses the app in a way that cannot be made to ask for
// the settings.
func (pl *appPlanner) shimStarts(src *appListenSource, mod goModule) (wrap []*appStartInfo, values []*appValueInfo, refusal appShimRefusal) {
	hits := func(o appOrigins) bool {
		return slices.ContainsFunc(o.news, func(n appNew) bool { return slices.Contains(src.creations, n) })
	}
	other := func(f *appFile) bool {
		m, ok := pl.moduleOf(f)
		return !ok || m.root != mod.root
	}

	crossing := func(started *appFile, o appOrigins) appShimRefusal {
		created := started
		for _, n := range o.news {
			if slices.Contains(src.creations, n) {
				created = n.file
				break
			}
		}
		return appShimRefusal{
			why: fmt.Sprintf("the app is created in %s and started in %s, which belong to different Go modules: "+
				"each module gets a registry of its own, and two of them cannot exchange values", appFileLabel(created), appFileLabel(started)),
			tell: true,
		}
	}

	for _, s := range pl.starts {
		switch hit := hits(s.origins); {
		case hit && other(s.file):
			return nil, nil, crossing(s.file, s.origins)
		case other(s.file):
		case hit, !s.origins.complete:
			wrap = append(wrap, s)
		}
	}

	for _, v := range pl.values {
		switch hit := hits(v.origins); {
		case other(v.file):
			if hit {
				return nil, nil, crossing(v.file, v.origins)
			}
		case !hit && v.origins.complete:
		case v.method == appNameListen || v.method == appNameListener:
			values = append(values, v)
		default:
			return nil, nil, appShimRefusal{
				why:  fmt.Sprintf("%s uses the method %s that starts an app as a value, at line %d", appFileLabel(v.file), v.method, v.file.g.line(v.sel.Pos())),
				tell: true,
			}
		}
	}

	// a start the registry cannot be asked from would run without the settings
	for _, pf := range pl.files {
		if other(pf) {
			continue
		}
		if line := pl.unknownStartOf(pf); line > 0 {
			return nil, nil, appShimRefusal{
				why:  fmt.Sprintf("the call at line %d of %s may start an app, but the type of its receiver is unknown", line, appFileLabel(pf)),
				tell: true,
			}
		}
	}
	if len(wrap) == 0 && len(values) == 0 && pl.reads[mod.root] == nil {
		return nil, nil, appShimRefusal{why: "no Listen call of this module starts the app, so it would hold the settings for nobody", tell: true, nobody: true}
	}

	// a call that sets the same setting itself says two things
	for _, s := range wrap {
		lit := s.explicitConfig()
		if lit == nil {
			continue
		}
		for _, fld := range src.fields {
			if idx, _ := appKeyedElement(lit, fld.v3); idx >= 0 {
				return nil, nil, appShimRefusal{
					why:  fmt.Sprintf("the fiber.ListenConfig of the call at line %d already sets %s", s.file.g.line(s.call.Pos()), fld.v3),
					tell: true,
				}
			}
		}
	}
	return wrap, values, appShimRefusal{}
}

// exposure returns the exported names of the packages of the module that other
// modules can import (the ones not in an internal directory, no main package)
// through which the apps the creations make can leave the module. Code outside the
// module starts such an app without the settings the registry holds.
func (pl *appPlanner) exposure(mod goModule, creations []appNew) []string {
	flows := func(o appOrigins) bool {
		return slices.ContainsFunc(o.news, func(n appNew) bool { return slices.Contains(creations, n) })
	}

	var out []string
	for _, pkg := range pl.publicPackages(mod) {
		label := appImportPathOf(mod, pkg)
		for _, d := range pkg.exportedAppAPI(flows) {
			out = append(out, label+"."+d)
		}
	}
	slices.Sort(out)
	return out
}

// publicPackages returns the packages of the module that other modules can import.
func (pl *appPlanner) publicPackages(mod goModule) []*appPackage {
	var out []*appPackage
	seen := map[*appPackage]bool{}
	for _, pf := range pl.files {
		pkg := pf.ix.pkgOf(pf)
		if pkg == nil || seen[pkg] {
			continue
		}
		seen[pkg] = true
		if m, ok := pl.moduleOf(pf); !ok || m.root != mod.root {
			continue
		}
		if pkg.name == appMainPackage || strings.HasSuffix(pkg.name, "_test") || slices.Contains(strings.Split(filepath.ToSlash(appRelDir(mod, pkg)), "/"), "internal") {
			continue
		}
		out = append(out, pkg)
	}
	slices.SortFunc(out, func(a, b *appPackage) int { return strings.Compare(a.dir, b.dir) })
	return out
}

// appRelDir is the directory of the package relative to the root of the module.
func appRelDir(mod goModule, pkg *appPackage) string {
	rel, err := filepath.Rel(mod.root, pkg.dir)
	if err != nil {
		return pkg.dir
	}
	return rel
}

// appImportPathOf is the import path of a package of the module.
func appImportPathOf(mod goModule, pkg *appPackage) string {
	rel := filepath.ToSlash(appRelDir(mod, pkg))
	if rel == "." {
		return mod.path
	}
	return mod.path + "/" + rel
}

// appShimNote is the note that tells about the registry, once for every module that
// gets one.
const appShimNote = "Prefork, Network, DisableStartupMessage and EnablePrintRoutes moved from fiber.Config to the fiber.ListenConfig that Listen takes in v3. " +
	"Some apps of this module get them away from the call that starts the app, so " + moduleShimDir + "/" + appShimFile + " was added to carry them: " +
	"fibermigrate." + appShimNew + " records them for the app and fibermigrate." + appShimConfig + " hands them to the Listen call that starts it. " +
	"Pass a fiber.ListenConfig to Listen yourself when you can, and delete the package when nothing uses it"

// note is the note of the registry of a module, with the functions that return its
// config and the way out of the module of the apps it holds.
func (sp *appShimModule) note() string {
	note := appShimNote
	var changes []string
	if len(sp.configs) > 0 {
		changes = append(changes, appNameList(sp.configs)+" now return"+appPlural(len(sp.configs))+" fibermigrate."+appShimConfigType)
	}
	if len(sp.takes) > 0 {
		changes = append(changes, appNameList(sp.takes)+" now take"+appPlural(len(sp.takes))+" a fibermigrate."+appShimConfigType)
	}
	if len(sp.holds) > 0 {
		changes = append(changes, appNameList(sp.holds)+" now hold"+appPlural(len(sp.holds))+" a fibermigrate."+appShimConfigType)
	}
	if len(changes) > 0 {
		note += ". " + strings.Join(changes, " and ") + ". fibermigrate." + appShimConfigType +
			" is the fiber.Config of Fiber v2 with the four settings, and fibermigrate." + appShimNewV2 + " hands them to the app it creates"
	}
	if len(sp.exposedConfigs) > 0 {
		note += ". " + appNameList(sp.exposedConfigs) + " can be called from other modules, which cannot hand the result to fiber.New: " +
			"they take its Config field and pass the settings to Listen"
	}
	if len(sp.exposedTypes) > 0 {
		note += ". " + appNameList(sp.exposedTypes) + " can be used from other modules, which cannot name fibermigrate." + appShimConfigType +
			" because " + moduleShimDir + " is internal: they pass a fiber.Config and the settings to Listen themselves"
	}
	if len(sp.exposed) > 0 {
		note += ". " + appNameList(sp.exposed) + " export" + appPlural(len(sp.exposed)) +
			" an app of the registry from a package other modules can import: their calls to Listen start it without these settings, " +
			"pass them in the fiber.ListenConfig of those calls"
	}
	return note
}

// appNameList joins the names the way a note shows them, at most three.
func appNameList(names []string) string {
	if len(names) <= 3 {
		return strings.Join(names, ", ")
	}
	return strings.Join(names[:3], ", ") + fmt.Sprintf(" and %d more", len(names)-3)
}

// appPlural is "s" for a verb that agrees with a single subject.
func appPlural(n int) string {
	if n == 1 {
		return "s"
	}
	return ""
}

// finishShims adds the calls that ask the registry for the settings, once every
// source has been planned: a call that can start apps of several sources is
// changed once.
func (pl *appPlanner) finishShims() {
	roots := make([]string, 0, len(pl.shims))
	for root := range pl.shims {
		roots = append(roots, root)
	}
	slices.Sort(roots)

	for _, root := range roots {
		sp := pl.shims[root]
		if sp.first != nil {
			internal.Notef(sp.first.file.fi, sp.first.file.g.line(sp.first.call.Pos()), "%s", sp.note())
		}
		for _, s := range sp.starts {
			fp := pl.plan.fileOf(s.file)

			// the call replaces its receiver, which can hold an app that another edit
			// makes: the receiver is rewritten with those edits, and they are left out
			receiver, rest := "", fp.edits.edits
			if !appPureReceiver(s.sel.X) {
				receiver, rest = appEditedText(fp.edits.edits, s.file.g, s.sel.X)
			}

			rw := s.rewriteShim(appImports{reqs: slices.Clone(fp.imps.reqs)}, receiver, sp.path)
			if rw.problem != "" {
				internal.Notef(s.file.fi, s.file.g.line(s.call.Pos()),
					"this call may start an app whose listener settings %s keeps, and it cannot ask for them: %s", moduleShimDir, rw.problem)
				continue
			}
			rest = append(rest, rw.edits...)
			fp.edits.edits = rest
			fp.imps = rw.imports
			for _, note := range rw.notes {
				internal.Notef(s.file.fi, s.file.g.line(s.call.Pos()), "%s", note)
			}
		}
		for _, v := range sp.values {
			fp := pl.plan.fileOf(v.file)
			receiver, rest := appEditedText(fp.edits.edits, v.file.g, v.sel.X)
			imps := appImports{reqs: slices.Clone(fp.imps.reqs)}
			rest = append(rest, v.rewrite(&imps, receiver, sp.path)...)
			fp.edits.edits = rest
			fp.imps = imps
		}
	}
}

// appEditedText returns the text of the node n with the edits that lie inside it
// applied, and the edits that do not.
func appEditedText(edits []textEdit, g *goSource, n ast.Node) (text string, rest []textEdit) {
	start, end := g.offset(n.Pos()), g.offset(n.End())

	var inside editSet
	for _, e := range edits {
		if e.start >= start && e.end <= end {
			inside.replace(e.start-start, e.end-start, e.text)
		} else {
			rest = append(rest, e)
		}
	}
	return inside.apply(g.src[start:end]), rest
}
